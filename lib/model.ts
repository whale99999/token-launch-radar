// Token Radar — the value model (radar-2).
//
// One snapshot in, one ranked board out. The board ranks only protocols whose
// DefiLlama record carries no token (no market cap, no CoinGecko id, no
// symbol). Protocols whose token already trades are kept apart in the Live
// view and shown at their market cap, never mixed into the ranking.
//
// Implied value follows only from the snapshot's own figures — TVL, the
// seven-day TVL change, how long the protocol has run with no token, and how
// many chains it runs on. No protocol name is ever special-cased: the same
// four functions score every row.
//
//   base          = tvl_usd x 0.30            (a 0.30x TVL multiple)
//   growthMult    = 1 + clamp(change_7d, -50, +150) / 100 x 0.80
//   maturityMult  = 0.70 + 0.30 x min(age_days, 1460) / 1460
//   chainMult     = 1 + 0.04 x min(max(chains - 1, 0), 5)
//   implied       = round(base x growthMult x maturityMult x chainMult)
//
// Why each term: TVL is the protocol's size today. Growth rewards momentum
// and punishes shrinkage, capped so one hot week cannot dominate. Maturity
// rewards survival: a protocol that has run for years with no token has
// earned the patience premium, while a 45-day-old protocol has not. Chain
// spread rewards distribution across chains, capped at five extra chains.
// Age is days from listed_at to the snapshot's as_of; an unlisted age uses
// 365 days. The result is capped at $100,000,000,000,000.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
